// One pipeline run, meant for GitHub Actions:
//   PREV_DIR: checkout of the previous `data` branch (may be empty on the first run)
//   OUT_DIR : where the new `data` branch content is written (public JSON + state)
// Reads the Tokenized Stocks API and Base over public endpoints. Needs no secrets.
import fs from "node:fs";
import path from "node:path";
import { runRefresh } from "../lib/refresh.js";
import { buildPublicFiles } from "../lib/publish.js";
import { FileStore } from "../lib/store.js";

const prevDir = process.env.PREV_DIR ?? "prev";
const outDir = process.env.OUT_DIR ?? "out";

const store = FileStore.load(path.join(prevDir, "state"));
console.log(`state loaded: ${store.keys().length} keys${store.keys().length === 0 ? " (first run)" : ""}`);

const doc = await runRefresh({ store });
const files = await buildPublicFiles(store, new Date().toISOString());

fs.mkdirSync(outDir, { recursive: true });
for (const [rel, content] of files) {
  const p = path.join(outDir, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
}
store.save(path.join(outDir, "state"));
fs.writeFileSync(
  path.join(outDir, "README.md"),
  "This branch is generated by the `readings` workflow and force-pushed as a single commit on every run. Do not edit it.\n" +
    "It holds public JSON that the Assay website and MCP server read. Not financial advice.\n",
);

const ok = doc.readings.filter((r) => r.status === "ok").length;
console.log(`published ${files.size} files; ${ok}/${doc.readings.length} reference tokens assayable; tokensApi=${doc.sources.tokensApi.ok} rpc=${doc.sources.rpc.ok}`);
